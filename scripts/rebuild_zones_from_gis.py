"""Regenerate app/zones.py with measured habitat attributes.

Reads the curated sector list (coordinates, aspect, popularity, access
notes) and joins it with the MFE50 + ICGC measurements cached in
data/habitat_gis.json (produced by scripts/ingest_habitat_data.py).
Zones without an MFE50 tree stand at or near their coordinates are
dropped: they are treeless farmland, bare karst or outside the four
Catalan provinces covered by the downloaded MFE50 sheets.

The forest label, canopy class, habitat quality, soil class, geology
description and tree-group shares are all derived from the measurements
via app.habitat. Everything else (names, coordinates, curated notes) is
carried over unchanged, so hand edits to notes survive re-runs.

Run from the project root:

    uv run python scripts/rebuild_zones_from_gis.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.habitat import (  # noqa: E402
    GROUPS,
    classify_soil,
    derive_cover,
    derive_forest,
    derive_habitat_quality,
    pine_composition,
)
from app.zones import ZONES  # noqa: E402

GIS_FILE = ROOT / "data" / "habitat_gis.json"
ZONES_FILE = ROOT / "app" / "zones.py"

HEADER = '''"""Curated mushroom sectors with measured habitat attributes.

Generated by scripts/rebuild_zones_from_gis.py — do not edit the derived
fields (forest, cover, habitat_quality, soil, forest_shares, geology,
forest_desc) by hand; edit data/habitat_gis.json inputs or the curated
fields (names, coordinates, aspect, popularity, accessibility, walk_min,
access, notes) and re-run the script.

Sources:
- MFE50 (Mapa Forestal de España 1:50.000, MITECO) — stand composition
  and canopy cover; © MITECO, free reuse with attribution.
- ICGC geology 1:50.000 — lithological unit at the centroid.
"""

from __future__ import annotations

from .models import Zone


def sector(
    id: str,
    name: str,
    area: str,
    comarca: str,
    lat: float,
    lon: float,
    elevation_m: int,
    aspect: str,
    forest: str,
    cover: str,
    habitat_quality: int,
    popularity: int,
    accessibility: int,
    walk_min: int,
    access: str,
    notes: str,
    soil: str = "neutral",
    forest_shares: dict[str, float] | None = None,
    geology: str = "",
    forest_desc: str = "",
) -> Zone:
    return Zone(
        id=id,
        name=name,
        area=area,
        comarca=comarca,
        lat=lat,
        lon=lon,
        elevation_m=elevation_m,
        aspect=aspect,
        forest=forest,
        cover=cover,
        habitat_quality=habitat_quality,
        popularity=popularity,
        accessibility=accessibility,
        walk_min=walk_min,
        access=access,
        notes=notes,
        soil=soil,
        forest_shares=forest_shares or {},
        geology=geology,
        forest_desc=forest_desc,
    )


ZONES: list[Zone] = [
'''


def fmt_shares(shares: dict[str, float]) -> str:
    items = [
        f'"{g}": {round(shares[g], 3)}' for g in GROUPS if shares.get(g, 0.0) >= 0.0005
    ]
    return "{" + ", ".join(items) + "}"


def main() -> None:
    gis = json.loads(GIS_FILE.read_text(encoding="utf-8"))["zones"]

    kept, dropped = [], []
    for z in ZONES:
        rec = gis.get(z.id)
        if not rec or not rec.get("mfe"):
            dropped.append(z.id)
            continue
        mfe, geol = rec["mfe"], rec.get("geol") or {}
        shares = pine_composition(mfe["species"])
        kept.append(
            {
                "zone": z,
                "forest": derive_forest(shares),
                "cover": derive_cover(mfe["tfccarb"]),
                "habitat_quality": derive_habitat_quality(mfe["tfccarb"]),
                "soil": classify_soil(geol.get("descripcio")),
                "forest_shares": fmt_shares(shares),
                "geology": geol.get("descripcio", ""),
                "forest_desc": mfe.get("formation", ""),
            }
        )

    lines = [HEADER]
    for rec in kept:
        z = rec["zone"]
        lines.append(
            f'    sector({z.id!r}, {z.name!r}, {z.area!r}, {z.comarca!r},\n'
            f"           {z.lat}, {z.lon}, {z.elevation_m}, {z.aspect!r}, "
            f'{rec["forest"]!r}, {rec["cover"]!r}, {rec["habitat_quality"]}, '
            f"{z.popularity}, {z.accessibility}, {z.walk_min},\n"
            f"           {z.access!r},\n"
            f"           {z.notes!r},\n"
            f'           soil={rec["soil"]!r}, forest_shares={rec["forest_shares"]},\n'
            f'           geology={rec["geology"]!r}, forest_desc={rec["forest_desc"]!r}),\n'
        )
    lines.append("]\n")
    lines.append(
        "\n\ndef get_zone(zone_id: str) -> Zone | None:\n"
        '    """Look up a sector by id."""\n'
        "    return next((z for z in ZONES if z.id == zone_id), None)\n"
    )

    ZONES_FILE.write_text("".join(lines), encoding="utf-8")
    print(f"wrote {len(kept)} zones to {ZONES_FILE}")
    if dropped:
        print(f"dropped {len(dropped)} zones without MFE50 data: {', '.join(dropped)}")


if __name__ == "__main__":
    main()
